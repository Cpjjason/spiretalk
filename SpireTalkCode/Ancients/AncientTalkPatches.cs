/// <summary>
/// Appends the "Talk" option to every Ancient's initial option page (single player only — a
/// shared multiplayer event can't wait on one player's private conversation).
/// </summary>
[HarmonyPatch(typeof(AncientEventModel), "GenerateInitialOptionsWrapper")]
internal static class AncientInitialOptionsPatch
{
    // Run after the option frameworks (RitsuLib / Ancient Affection) so our option is appended to
    // whatever list they produce instead of being rebuilt away by a later postfix.
    [HarmonyPostfix]
    [HarmonyPriority(Priority.Last)]
    [HarmonyAfter("com.ritsukage.sts2-RitsuLib.framework-core", "AncientAffection.harmony")]
    private static void AppendTalkOption(AncientEventModel __instance, ref IReadOnlyList<EventOption> __result)
    {
        try
        {
            if (!SpireTalkConfig.EnableAncients) return;
            var owner = __instance.Owner;
            if (owner == null || owner.RunState.Players.Count > 1) return;
            if (__result.Count == 0) return;
            // Only the PROCEED page (ancient blocked by Wax Choker etc.) has a single proceed option.
            if (__result.Count == 1 && __result[0].IsProceed) return;
            // A reroll from before a reload: show the rerolled page again (and skip the inner call).
            if (!AncientConversation.ReplayReroll(__instance, ref __result)) return;
            // Lines for this room already spent (page regenerated by a relic reroll).
            if (!AncientConversation.CanOfferTalk(__instance)) return;

            // New list on purpose: the game keeps a reference to its own list for run-history
            // bookkeeping, and our option must not appear there.
            var withTalk = new List<EventOption>(__result.Count + 1);
            withTalk.AddRange(__result);
            withTalk.Add(AncientConversation.CreateTalkOption(__instance, __result));
            __result = withTalk;
        }
        catch (Exception ex)
        {
            MainFile.Logger.Error($"[Talk] could not append talk option: {ex}", 1);
        }
    }
}

/// <summary>
/// Ancient Affection inserts its marriage-status option into every option page it sees (it
/// patches NEventLayout.AddOptions). Inside a SpireTalk conversation page that option makes no
/// sense, so strip its options there. Runs after AA's prefix (Priority.Last) so the list it
/// produced is what gets filtered.
/// </summary>
[HarmonyPatch(typeof(NEventLayout), "AddOptions")]
internal static class ConversationPageOptionsPatch
{
    [HarmonyPrefix]
    [HarmonyPriority(Priority.Last)]
    private static void KeepConversationPageOurs(ref IEnumerable<EventOption> options)
    {
        try
        {
            var list = options as List<EventOption> ?? options.ToList();
            if (!list.Any(o => o.TextKey is "SPIRETALK_CHOICE" or "SPIRETALK_END")) return;
            list.RemoveAll(o => o.TextKey.StartsWith("ANCIENT_AFFECTION", StringComparison.OrdinalIgnoreCase));
            options = list;
        }
        catch
        {
            // cosmetic only
        }
    }
}

/// <summary>Make sure the typed line is in the option list before the layout measures it.</summary>
[HarmonyPatch(typeof(NAncientEventLayout), "SetDialogueLineAndAnimate")]
internal static class AncientDialoguePagePatch
{
    [HarmonyPrefix]
    private static void BeforePage(NAncientEventLayout __instance)
    {
        try
        {
            AncientConversation.BeforeDialoguePage(__instance);
        }
        catch
        {
            // cosmetic only
        }
    }

    private static readonly System.Reflection.FieldInfo? DialogueField = AccessTools.Field(typeof(NAncientEventLayout), "_dialogue");

    [HarmonyPostfix]
    private static void AfterPage(NAncientEventLayout __instance, int lineIndex)
    {
        try
        {
            if (DialogueField?.GetValue(__instance) is System.Collections.ICollection lines && lineIndex >= lines.Count - 1)
            {
                AncientConversation.OnLastDialoguePage(__instance);
            }
        }
        catch (Exception ex)
        {
            MainFile.Logger.Warn($"[Talk] last-page hook: {ex.Message}", 1);
        }
    }
}

/// <summary>Drop per-event conversation state when the room goes away.</summary>
[HarmonyPatch(typeof(NEventRoom), "_ExitTree")]
internal static class EventRoomExitPatch
{
    [HarmonyPrefix]
    private static void ForgetConversation(NEventRoom __instance)
    {
        try
        {
            var field = AccessTools.Field(typeof(NEventRoom), "_event");
            if (field?.GetValue(__instance) is AncientEventModel ancient)
            {
                AncientConversation.Forget(ancient);
            }
        }
        catch
        {
            // best effort
        }
    }
}
