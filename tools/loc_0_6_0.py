PREFIX = "SPIRETALK-MSG."


def main():
    langs = sorted(os.listdir(ROOT))
    keys = list(T["eng"].keys())
    for lang in langs:
        strings = T.get(lang)
        assert strings is not None, f"no 0.6.0 strings for {lang}"
        missing = [k for k in keys if k not in strings]
        assert not missing, (lang, missing)
        for k in keys:
            for ph in ("{0}", "{1}"):
                assert (ph in T["eng"][k]) == (ph in strings[k]), (lang, k, ph)
        path = os.path.join(ROOT, lang, "settings_ui.json")
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        for k in keys:
            data[PREFIX + k] = strings[k]
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(lang, len(data))


if __name__ == "__main__":
    main()
