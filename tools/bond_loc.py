NAMES = {"NEOW": "NEOW", "DARV": "DARV", "VAKUU": "VAKUU"}
SEP = {"zhs": "", "zht": "", "jpn": "", "tha": " "}


def main():
    loc = sys.argv[1]
    def table(lang, name):
        p = os.path.join(loc, lang, name + ".json")
        return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else {}
    eng_rel, eng_anc, eng_lib = table("eng", "relics"), table("eng", "ancients"), table("eng", "card_library")
    for lang in LANGS:
        rel, anc, lib = table(lang, "relics"), table(lang, "ancients"), table(lang, "card_library")
        def fill(s):
            for k in NAMES:
                s = s.replace(f"<<{k}>>", anc.get(f"{k}.title") or eng_anc.get(f"{k}.title") or k.title())
            for r in ("COMMON", "UNCOMMON", "RARE"):
                s = s.replace(f"<<{r}>>", lib.get(f"RARITY_{r}") or eng_lib.get(f"RARITY_{r}") or r.title())
            return s
        def text(key):
            if key.startswith("@"):
                return rel.get(key[1:] + ".description") or eng_rel[key[1:] + ".description"]
            return fill(T[key].get(lang) or T[key]["eng"])
        sep = SEP.get(lang, " ")
        out_path = os.path.join(ROOT, "SpireTalk", "localization", lang, "relics.json")
        out = json.load(open(out_path, encoding="utf-8"), object_pairs_hook=OrderedDict)
        for k in [k for k in out if k.startswith("SPIRETALK-BOND.") or k.startswith("SPIRETALK-DEVOTED_") or k.startswith("SPIRETALK-BELOVED_")]:
            del out[k]
        out["SPIRETALK-BOND.tier2.title"] = T["tier2"][lang]
        out["SPIRETALK-BOND.tier3.title"] = T["tier3"][lang]
        for rid, plan in PLAN.items():
            vanilla = plan[0]
            v = lambda suffix: rel.get(f"{vanilla}.{suffix}") or eng_rel.get(f"{vanilla}.{suffix}")
            title = v("title")
            for tier, parts, base_key in (("DEVOTED", plan[1], None), ("BELOVED", plan[2], plan[3] if len(plan) > 3 else None)):
                key = f"SPIRETALK-{tier}_{rid}"
                extra = sep.join(text(p) for p in parts)
                def compose(base):
                    return base if not extra else base + "\n" + extra
                if base_key:
                    desc = event = text(base_key)
                    desc, event = compose(desc), compose(event)
                else:
                    desc = compose(v("description"))
                    event = compose(v("eventDescription")) if v("eventDescription") else None
                out[f"{key}.title"] = (T["tier2" if tier == "DEVOTED" else "tier3"][lang]).replace("{Relic}", title)
                out[f"{key}.description"] = desc
                if event: out[f"{key}.eventDescription"] = event
                for extra_key in ("selectionScreenPrompt",):
                    if v(extra_key): out[f"{key}.{extra_key}"] = v(extra_key)
                out[f"{key}.flavor"] = v("flavor") or ""
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(lang, "ok")


if __name__ == "__main__":
    main()
